"""F228: tools/sync-piracy-list.py turns a saved git tree of cnstr/manifests into core/piracy-list.js. Never fetches."""
import importlib.util
import io
import json
import re
import tempfile
import unittest
from pathlib import Path
from unittest import mock

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("sync_piracy_list", HERE / "sync-piracy-list.py")
sync = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sync)

SHA = "f517ff676e478ab826cdb3d2a2e8cec175dd0969"
COMMITS = [{"sha": SHA, "commit": {"committer": {"date": "2025-09-01T12:00:00Z"}}}]


def tree(*names, extra=()):
    items = [{"path": "configs/piracy-list/" + n, "type": "blob"} for n in names]
    return {"truncated": False, "tree": items + list(extra)}


class SyncPiracyList(unittest.TestCase):
    def test_hosts_from_tree(self):
        t = tree("repo.hackyouriphone.org", "WWW.Example.COM", "n3d1117.github.io", "github.io", "not a host",
                 extra=[{"path": "configs/piracy-list", "type": "tree"},
                        {"path": "configs/index-list/chariz.yaml", "type": "blob"},
                        {"path": "configs/piracy-list/sub/x.org", "type": "blob"}])
        hosts, bad, left = sync.hosts_from_tree(t)
        self.assertEqual(hosts, ["example.com", "repo.hackyouriphone.org"])
        self.assertEqual(bad, ["not a host"])
        self.assertEqual(left, ["github.io", "n3d1117.github.io"])

    def test_truncated_tree_is_refused(self):
        with self.assertRaises(SystemExit):
            sync.hosts_from_tree({"truncated": True, "tree": []})

    def test_writes_module_with_notice_and_commit(self):
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            (d / "tree.json").write_text(json.dumps(tree("b.example.net", "a.example.org")))
            (d / "commits.json").write_text(json.dumps(COMMITS))
            out = d / "piracy-list.js"
            sync.main(["--tree", str(d / "tree.json"), "--commits", str(d / "commits.json"), "--out", str(out)])
            js = out.read_text()
        self.assertIn("MIT License", js)
        self.assertIn("Copyright (c) 2022 Aerum LLC", js)
        self.assertIn(f'commit: "{SHA}", date: "2025-09-01"', js)
        self.assertEqual(re.findall(r'^  "([^"]+)",$', js, re.M), ["a.example.org", "b.example.net"])

    def test_bad_commit_answer_is_refused(self):
        with self.assertRaises(SystemExit):
            sync.last_commit([])

    def _sent_headers(self, env):
        """The headers fetch_json sends with this environment (urlopen patched: nothing goes out)."""
        sent = []

        def fake_urlopen(req, timeout=None):
            sent.append({k.lower(): v for k, v in req.header_items()})
            return io.BytesIO(b"[]")

        with mock.patch.dict(sync.os.environ, env, clear=True), \
                mock.patch.object(sync.urllib.request, "urlopen", fake_urlopen):
            self.assertEqual(sync.fetch_json(sync.COMMITS_URL), [])
        return sent[0]

    def test_gh_token_goes_out_as_authorization(self):
        h = self._sent_headers({"GH_TOKEN": "gho_example"})
        self.assertEqual(h["authorization"], "Bearer gho_example")
        self.assertEqual(h["accept"], "application/vnd.github+json")

    def test_no_gh_token_no_authorization(self):
        self.assertNotIn("authorization", self._sent_headers({}))
        self.assertNotIn("authorization", self._sent_headers({"GH_TOKEN": "  "}))

    def test_committed_module_is_generated_shape(self):
        js = (HERE.parent / "web" / "app" / "core" / "piracy-list.js").read_text()
        self.assertTrue(js.startswith("// Generated by tools/sync-piracy-list.py"))
        hosts = re.findall(r'^  "([^"]+)",$', js, re.M)
        self.assertEqual(hosts, sorted(set(hosts)))
        for h in hosts:
            self.assertRegex(h, sync.HOST)
            self.assertNotIn(h, sync.NOT_COPIED)
            self.assertNotIn(h, sync.SHARED_SUFFIXES)


if __name__ == "__main__":
    unittest.main()
